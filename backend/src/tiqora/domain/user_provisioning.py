"""The one write path for Znuny agents, roles, groups and customer users (wave 1, D17).

Admin routes, SSO just-in-time provisioning and role/group sync all go through here so
the rows land exactly as Znuny itself writes them (``Kernel::System::User::UserAdd``,
``Group::PermissionRoleUserAdd`` / ``PermissionGroupUserAdd``,
``CustomerUser::DB::CustomerUserAdd``):

* timestamps are naive UTC, ``create_by`` / ``change_by`` carry the actor;
* ``UserAdd`` requires an e-mail address and syntax-checks it for valid accounts;
* a ``group_user`` permission write replaces the whole key set of one (user, group)
  pair, and ``rw`` is stored alone because it includes every other key;
* every write enqueues the same Znuny cache-type invalidations the admin routes did.

Functions flush but never commit; the caller owns the transaction. The 7.1+ surrogate
``id`` of the junction tables is generated by the database, so the ORM inserts work on
every schema profile; reads select explicit columns only.
"""

from __future__ import annotations

import re
from datetime import datetime

from sqlalchemy import delete, func, select
from sqlalchemy.ext.asyncio import AsyncSession

from tiqora.api.v1.admin.common import (
    CUSTOMER_USER_CACHE_TYPES,
    USER_CACHE_TYPES,
    USER_GROUP_CACHE_TYPES,
    USER_ROLE_CACHE_TYPES,
    invalidate_znuny_cache_types,
    now,
)
from tiqora.channels.phone.cti import PHONE_EXTENSION_PREF
from tiqora.db.legacy.customer import CustomerUser
from tiqora.db.legacy.user import GroupUser, PermissionGroups, Roles, RoleUser, Users
from tiqora.db.tiqora.models import TiqoraIdentityManagedAssignment
