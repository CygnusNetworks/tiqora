from tiqora.znuny.sysconfig import SysConfig

VALID_ID = 1

# Defaults.pm / Framework.xml values of the settings CheckEmail reads.
_DEFAULT_VALID_ADDRESS = r"^(root@localhost|admin@localhost)$"
_DEFAULT_INVALID_ADDRESS = r"@(example)\.(..|...)$"

_ATOM = r"[A-Za-z0-9!#$%&'*+/=?^_`{|}~-]+"
_LABEL = r"[A-Za-z0-9](?:[A-Za-z0-9-]*[A-Za-z0-9])?"
# addr-spec: dot-atom local part, dotted domain (or IP literal). A bare "user@host" is
# rejected like Email::Valid does without -allow_localhost.
_SYNTAX_RE = re.compile(rf"^{_ATOM}(?:\.{_ATOM})*@(?:(?:{_LABEL}\.)+{_LABEL}|\[[0-9.]+\])$")
_TRAILING_COMMENT_RE = re.compile(r"\s*\([^()]*\)\s*$")


class ProvisioningError(ValueError):
    """A write Znuny itself would refuse. ``code`` is machine-readable."""

    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code = code


def _perl_true(value: object) -> bool:
    """Perl truthiness of a SysConfig value ("", "0", 0, None are false)."""
    return value not in (None, "", "0", 0, False)


def _perl_match(pattern: object, text_: str) -> bool:
    if not isinstance(pattern, str) or not pattern:
        return False
    try:
        return re.search(pattern, text_, re.IGNORECASE) is not None
    except re.error:
        return False


async def check_email(session: AsyncSession, address: str) -> bool:
    """Port of Znuny ``CheckItem::CheckEmail`` driven by SysConfig (DB, Znuny defaults).

    Order as in Znuny: ``CheckEmailAddresses`` off -> accept; ``CheckEmailValidAddress``
    whitelist -> accept; syntax (plus the ``(\\.\\.)|(\\.@)`` rule); then
    ``CheckEmailInvalidAddress`` -> reject. The MX/DNS lookup (``CheckMXRecord``) is
    deliberately NOT performed (no network access from a request handler).
    """
    sysconfig = SysConfig(session)
    if not _perl_true(await sysconfig.get("CheckEmailAddresses", 1)):
        return True
    if _perl_match(await sysconfig.get("CheckEmailValidAddress", _DEFAULT_VALID_ADDRESS), address):
        return True
    candidate = _TRAILING_COMMENT_RE.sub("", address)
    if not _SYNTAX_RE.match(candidate) or re.search(r"(\.\.)|(\.@)", candidate):
        return False
    return not _perl_match(
        await sysconfig.get("CheckEmailInvalidAddress", _DEFAULT_INVALID_ADDRESS), candidate
    )


async def _require_valid_email(session: AsyncSession, address: str, valid_id: int) -> None:
    # UserAdd / CustomerUserAdd only check accounts that are going to be valid.
    if valid_id == VALID_ID and not await check_email(session, address):
        raise ProvisioningError("email_invalid", f"Email address ({address}) not valid")


async def _customer_email_in_use(
    session: AsyncSession, address: str, *, exclude_id: int | None = None
) -> bool:
    """``CustomerUserEmailUniqCheck`` (Znuny default on): any customer user, valid or not."""
    cfg = await SysConfig(session).get("CustomerUser")
    enabled = cfg.get("CustomerUserEmailUniqCheck", 1) if isinstance(cfg, dict) else 1
    if not _perl_true(enabled):
        return False
    stmt = select(CustomerUser.id).where(func.lower(CustomerUser.email) == address.lower())
    if exclude_id is not None:
        stmt = stmt.where(CustomerUser.id != exclude_id)
    return (await session.execute(stmt.limit(1))).first() is not None


_EMAIL_IN_USE = "Diese E-Mail-Adresse wird bereits von einem anderen Kundenbenutzer verwendet."


async def create_agent(
    session: AsyncSession,
    *,
    login: str,
    first_name: str,
    last_name: str,
    email: str | None,
    mobile: str | None,
    title: str | None,
    pw_hash: str,
    valid_id: int,
    actor_id: int,
    phone_extension: str | None = None,
    require_email: bool = False,
) -> Users:
    """``users`` row plus ``UserEmail`` / ``UserMobile`` / extension preferences.

    ``require_email`` mirrors ``UserAdd`` (``UserEmail`` is a needed parameter); the
    admin route keeps allowing a password-only account without address, so it is opt-in
    there and on for provisioning.
    """
    first_name, last_name, login = first_name.strip(), last_name.strip(), login.strip()
    if not first_name or not last_name:
        raise ProvisioningError("name_required", "Need UserFirstname and UserLastname!")
    email = email.strip() if email else email
    if require_email and not email:
        raise ProvisioningError("email_required", "Need UserEmail!")
    if email:
        await _require_valid_email(session, email, valid_id)
    exists = (
        await session.execute(select(Users.id).where(func.lower(Users.login) == login.lower()))
    ).first()
    if exists is not None:
        raise ProvisioningError(
            "login_exists", f"A user with the username '{login}' already exists."
        )

    ts = now()
    user = Users(
        login=login,
        pw=pw_hash,
        title=title,
        first_name=first_name,
        last_name=last_name,
        valid_id=valid_id,
        create_time=ts,
        create_by=actor_id,
        change_time=ts,
        change_by=actor_id,
    )
    session.add(user)
    await session.flush()  # assigns user.id for the preference rows below

    if email:
        await set_preference(session, user.id, "UserEmail", email)
    if mobile:
        await set_preference(session, user.id, "UserMobile", mobile)
    if phone_extension:
        await set_preference(session, user.id, PHONE_EXTENSION_PREF, phone_extension)

    await invalidate_znuny_cache_types(session, USER_CACHE_TYPES)
    await session.flush()
    return user


async def update_agent_profile(
    session: AsyncSession,
    user: Users,
    *,
    first_name: str | None,
    last_name: str | None,
    email: str | None,
    mobile: str | None,
    actor_id: int,
) -> bool:
    """Apply name / e-mail / mobile; ``None`` leaves a value alone, ``""`` clears a preference.

    Returns True when something changed. An unchanged call writes nothing (so
    ``change_time`` keeps its value) and enqueues no invalidation.
    """
    changed = False
    if first_name is not None and first_name != user.first_name:
        user.first_name = first_name
        changed = True
    if last_name is not None and last_name != user.last_name:
        user.last_name = last_name
        changed = True
    for key, value in (("UserEmail", email), ("UserMobile", mobile)):
        if value is None:
            continue
        value = value.strip()
        current = await get_preference(session, user.id, key)
        if (current or "") == value:
            continue
        if key == "UserEmail" and value:
            await _require_valid_email(session, value, user.valid_id)
        await set_preference(session, user.id, key, value)
        changed = True
    if changed:
        user.change_time = now()
        user.change_by = actor_id
        await invalidate_znuny_cache_types(session, USER_CACHE_TYPES)
        await session.flush()
    return changed


async def grant_role(session: AsyncSession, *, user_id: int, role_id: int, actor_id: int) -> bool:
    """Add a ``role_user`` row. False (and no invalidation) when it already exists."""
    present = (
        await session.execute(
            select(RoleUser.user_id).where(RoleUser.user_id == user_id, RoleUser.role_id == role_id)
        )
    ).first()
    if present is not None:
        return False
    ts = now()
    session.add(
        RoleUser(
            user_id=user_id,
            role_id=role_id,
            create_time=ts,
            create_by=actor_id,
            change_time=ts,
            change_by=actor_id,
        )
    )
    await invalidate_znuny_cache_types(session, USER_ROLE_CACHE_TYPES)
    await session.flush()
    return True


async def revoke_role(session: AsyncSession, *, user_id: int, role_id: int) -> bool:
    result = await session.execute(
        delete(RoleUser).where(RoleUser.user_id == user_id, RoleUser.role_id == role_id)
    )
    if not result.rowcount:  # type: ignore[attr-defined]
        return False
    await invalidate_znuny_cache_types(session, USER_ROLE_CACHE_TYPES)
    await session.flush()
    return True


async def _group_keys(session: AsyncSession, user_id: int, group_id: int) -> frozenset[str]:
    rows = await session.execute(
        select(GroupUser.permission_key).where(
            GroupUser.user_id == user_id, GroupUser.group_id == group_id
        )
    )
    return frozenset(str(k) for (k,) in rows.all())


async def set_group_permissions(
    session: AsyncSession,
    *,
    user_id: int,
    group_id: int,
    permission_keys: frozenset[str] | set[str],
    actor_id: int,
) -> bool:
    """``PermissionGroupUserAdd``: replace the whole key set of one (user, group) pair.

    ``rw`` is stored alone (Znuny deletes everything else then). Keys are taken as given
    so site-defined permission types survive; callers validate new keys. Identical sets
    are a no-op.
    """
    wanted = set(permission_keys)
    if "rw" in wanted:
        wanted = {"rw"}
    current = await _group_keys(session, user_id, group_id)
    if current == wanted:
        return False
    await session.execute(
        delete(GroupUser).where(GroupUser.user_id == user_id, GroupUser.group_id == group_id)
    )
    ts = now()
    for key in sorted(wanted):
        session.add(
            GroupUser(
                user_id=user_id,
                group_id=group_id,
                permission_key=key,
                create_time=ts,
                create_by=actor_id,
                change_time=ts,
                change_by=actor_id,
            )
        )
    await invalidate_znuny_cache_types(session, USER_GROUP_CACHE_TYPES)
    await session.flush()
    return True


async def grant_group_permission(
    session: AsyncSession, *, user_id: int, group_id: int, permission_key: str, actor_id: int
) -> bool:
    """Add one key to the pair's set (Znuny semantics: ``rw`` collapses the set to ``rw``,
    and any key under an existing ``rw`` is already included)."""
    if permission_key not in PERMISSION_KEYS:
        raise ProvisioningError("permission_unknown", f"Unknown permission key {permission_key!r}")
    current = await _group_keys(session, user_id, group_id)
    return await set_group_permissions(
        session,
        user_id=user_id,
        group_id=group_id,
        permission_keys=current | {permission_key},
        actor_id=actor_id,
    )


async def revoke_group_permission(
    session: AsyncSession, *, user_id: int, group_id: int, permission_key: str
) -> bool:
    result = await session.execute(
        delete(GroupUser).where(
            GroupUser.user_id == user_id,
            GroupUser.group_id == group_id,
            GroupUser.permission_key == permission_key,
        )
    )
    if not result.rowcount:  # type: ignore[attr-defined]
        return False
    await invalidate_znuny_cache_types(session, USER_GROUP_CACHE_TYPES)
    await session.flush()
    return True


async def current_roles(session: AsyncSession, user_id: int) -> frozenset[int]:
    rows = await session.execute(select(RoleUser.role_id).where(RoleUser.user_id == user_id))
    return frozenset(int(r) for (r,) in rows.all())


async def current_group_perms(session: AsyncSession, user_id: int) -> frozenset[tuple[int, str]]:
    rows = await session.execute(
        select(GroupUser.group_id, GroupUser.permission_key).where(GroupUser.user_id == user_id)
    )
    return frozenset((int(g), str(k)) for g, k in rows.all())


async def valid_role_ids(session: AsyncSession) -> frozenset[int]:
    rows = await session.execute(select(Roles.id).where(Roles.valid_id == VALID_ID))
    return frozenset(int(r) for (r,) in rows.all())


async def valid_group_ids(session: AsyncSession) -> frozenset[int]:
    rows = await session.execute(
        select(PermissionGroups.id).where(PermissionGroups.valid_id == VALID_ID)
    )
    return frozenset(int(r) for (r,) in rows.all())


async def create_customer_user(
    session: AsyncSession,
    *,
    login: str,
    email: str,
    customer_id: str,
    first_name: str,
    last_name: str,
    pw_hash: str | None,
    actor_id: int,
    valid_id: int = VALID_ID,
    **optional: str | None,
) -> CustomerUser:
    """``customer_user`` row (``CustomerUserAdd``). ``optional``: title, phone, fax, mobile,
    street, zip, city, country, comments."""
    allowed = {"title", "phone", "fax", "mobile", "street", "zip", "city", "country", "comments"}
    unknown = set(optional) - allowed
    if unknown:
        raise TypeError(f"unknown customer fields: {sorted(unknown)}")
    login, email = login.strip(), email.strip()
    if email:
        await _require_valid_email(session, email, valid_id)
        if await _customer_email_in_use(session, email):
            raise ProvisioningError("email_in_use", _EMAIL_IN_USE)
    ts: datetime = now()
    cu = CustomerUser(
        login=login,
        email=email,
        customer_id=customer_id,
        first_name=first_name,
        last_name=last_name,
        pw=pw_hash,
        valid_id=valid_id,
        create_time=ts,
        create_by=actor_id,
        change_time=ts,
        change_by=actor_id,
        **optional,
    )
    session.add(cu)
    await invalidate_znuny_cache_types(session, CUSTOMER_USER_CACHE_TYPES)
    await session.flush()
    return cu


async def update_customer_profile(
    session: AsyncSession,
    cu: CustomerUser,
    *,
    first_name: str | None,
    last_name: str | None,
    email: str | None,
    mobile: str | None,
    actor_id: int,
) -> bool:
    """Apply name / e-mail / mobile to a customer user; ``None`` leaves a value alone."""
    changed = False
    for field, value in (
        ("first_name", first_name),
        ("last_name", last_name),
        ("email", email),
        ("mobile", mobile),
    ):
        if value is None or getattr(cu, field) == value:
            continue
        value = value.strip()
        if getattr(cu, field) == value:
            continue
        if field == "email" and value:
            await _require_valid_email(session, value, cu.valid_id)
            if await _customer_email_in_use(session, value, exclude_id=cu.id):
                raise ProvisioningError("email_in_use", _EMAIL_IN_USE)
        setattr(cu, field, value)
        changed = True
    if changed:
        cu.change_time = now()
        cu.change_by = actor_id
        await invalidate_znuny_cache_types(session, CUSTOMER_USER_CACHE_TYPES)
        await session.flush()
    return changed


async def record_managed_assignment(
    session: AsyncSession,
    *,
    provider_id: int,
    user_kind: str,
    user_id: int,
    kind: str,
    target_id: int,
    permission_key: str,
) -> TiqoraIdentityManagedAssignment:
    """Mark a role/group assignment as created by a provider rule.

    Managed assignments exist for agents only: ``tiqora_identity_managed_assignment`` has
    no ``user_kind`` column, so a customer id would be indistinguishable from an agent
    id (and ``user_delete`` purges rows by ``user_id`` alone). Customers are rejected.
    """
    if user_kind != "agent":
        raise ProvisioningError(
            "managed_agent_only", "Managed assignments are only supported for agents"
        )
    row = TiqoraIdentityManagedAssignment(
        provider_id=provider_id,
        user_id=user_id,
        kind=kind,
        target_id=target_id,
        permission_key=permission_key,
        created=now(),
    )
    session.add(row)
    await session.flush()
    return row
