HASH = "--hash=sha256:" + "ab" * 32


def _txt(d: Path, content: str) -> Path:
    path = d / "plugins.txt"
    path.write_text(content)
    return path


def _dist(name: str, version: str) -> types.SimpleNamespace:
    return types.SimpleNamespace(metadata={"Name": name}, version=version)


def test_parse_plugins_txt(tmp_path: Path) -> None:
    (tmp_path / "wheels").mkdir()
    (tmp_path / "wheels" / "hello-1.0.0-py3-none-any.whl").write_bytes(b"PK")
    txt = _txt(
        tmp_path,
        "# Kommentar\n\n--index-url https://pypi.example.org/simple\n"
        "org-example-crm==2.1.0\nmatrix-plugin @ https://example.org/m-1.0-py3-none-any.whl\n"
        "./wheels/hello-1.0.0-py3-none-any.whl\n",
    )
    parsed = parse_plugins_txt(txt)
    assert parsed.lines == [
        "--index-url https://pypi.example.org/simple",
        "org-example-crm==2.1.0",
        "matrix-plugin @ https://example.org/m-1.0-py3-none-any.whl",
        "/tmp/tiqora-plugins/wheels/hello-1.0.0-py3-none-any.whl",
    ]
    assert [w.name for w in parsed.wheels] == ["hello-1.0.0-py3-none-any.whl"]


def test_parse_passes_hashes_through(tmp_path: Path) -> None:
    (tmp_path / "x-1.0-py3-none-any.whl").write_bytes(b"PK")
    parsed = parse_plugins_txt(
        _txt(tmp_path, f"crm==2.1.0 {HASH}\n./x-1.0-py3-none-any.whl {HASH}\n")
    )
    assert parsed.lines == [
        f"crm==2.1.0 {HASH}",
        f"/tmp/tiqora-plugins/wheels/x-1.0-py3-none-any.whl {HASH}",
    ]


@pytest.mark.parametrize(
    ("line", "message"),
    [
        ("-e ./src", "nicht erlaubt"),
        ("-r other.txt", "nicht erlaubt"),
        ("-c c.txt", "nicht erlaubt"),
        ("--no-deps", "nicht erlaubt"),
        ("--pre", "nicht erlaubt"),
        ("--trusted-host x", "nicht erlaubt"),
        ("./missing-1.0-py3-none-any.whl", "nicht gefunden"),
        ("--extra-index-url https://git.example.org/simple", "--extra-index-url"),
        ("crm @ git+https://git.example.org/crm.git", "gebautes Wheel"),
        ("git+https://git.example.org/crm.git", "gebautes Wheel"),
        ("crm==1.0 --hash=sha256:xyz", "--hash"),
        ("crm==1.0 --no-binary", "--hash"),
        ("./src", "Wheel"),
        ("https://example.org/m-1.0-py3-none-any.whl", "name @"),
    ],
)
def test_parse_rejects(tmp_path: Path, line: str, message: str) -> None:
    with pytest.raises(BakeError, match="Zeile 1") as exc:
        parse_plugins_txt(_txt(tmp_path, line + "\n"))
    assert message in str(exc.value)


def test_parse_rejects_second_index_url(tmp_path: Path) -> None:
    txt = _txt(
        tmp_path, "--index-url https://a.example.org/s\n--index-url https://b.example.org/s\n"
    )
    with pytest.raises(BakeError, match="Zeile 2"):
        parse_plugins_txt(txt)


def test_render_dockerfile_exact() -> None:
    assert render_dockerfile("ghcr.io/cygnusnetworks/tiqora:0.18.2", has_wheels=True) == (
        "# Generated by `tiqora plugins bake` — edit plugins.txt and run it again "
        "instead of editing this file.\n"
        "FROM ghcr.io/cygnusnetworks/tiqora:0.18.2\n"
        "USER root\n"
        "COPY plugins.txt /tmp/tiqora-plugins/plugins.txt\n"
        "COPY wheels/ /tmp/tiqora-plugins/wheels/\n"
        "RUN /app/.venv/bin/python -m ensurepip --upgrade \\\n"
        " && /app/.venv/bin/python -m pip install --no-cache-dir \\\n"
        "      --constraint /app/backend/core-constraints.txt \\\n"
        "      -r /tmp/tiqora-plugins/plugins.txt \\\n"
        " && /app/.venv/bin/python -m pip uninstall -y pip \\\n"
        " && rm -rf /tmp/tiqora-plugins\n"
        "USER tiqora\n"
        "RUN python -m tiqora.main plugins verify --import --strict\n"
    )
    assert "COPY wheels/" not in render_dockerfile("x", has_wheels=False)


